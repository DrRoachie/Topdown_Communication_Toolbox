% main loop 1: Run for all sessions

for rd = 1:length(session_info(:,1))

    % Establish the subset of data that you want to process. 
    Animal           = session_info{rd,1};                  % Options: 'MrCassius', 'MrM'; 
    RecDate          = session_info{rd,2};                  % Options: 'YYMMDD'; 
    Epoch            = session_info{rd,3};                  % Options: 'testToneOnset', 'preCueOnset', or 'moveOnset'
    Behavior         = session_info{rd,4};                  % Options:  'Correct', Wrong, due to memory constraints                          
    RandomIteration  = 300;                                 % Options: the number of times you want to allocate the random partition, and generate the test statistic
    %SNR             = [-1.5000, -1.2500, 1.2500, 1.5000];  % Options: any combination of  -11/6, -5/3, -1.5000, -1.2500, 0, 1.2500, 1.5000, 5/3, 11/6; default all
    SNR               = [-11/6, -5/3, 5/3, 11/6];            % Options: any combination of  -11/6, -5/3, -1.5000, -1.2500, 0, 1.2500, 1.5000, 5/3, 11/6; default all
    freq_band_list   = session_info{rd,5};
    threshold_value  = 0.5;                                 % the threshold used for the monte carlo test between PriorOnly and PretoneOnly Conditions

    % Set directory and get a list of all files in the folder with the desired file name pattern.
    datadir = fullfile('D:\04_Epoc_Cut', Animal, extractBefore(Epoch, 'Onset'), RecDate); % epoch data, with the time chunk that you want isolated
    chandir = fullfile('D:\05_Significant_Channels', Behavior, Animal, extractBefore(Epoch, 'Onset'), RecDate);                                             % the sig channels that are output LFP_Spectral_Analysis
    specdir = fullfile('D:\02_Preprocessed', Animal, Epoch);                             % this is where the uncut preprocessed data is stored; you need the full time series for the spectogram
    savedir = 'C:\Users\Corey Roach\Documents\00_DATA\PretoneOnly_LED_HighSNR_Correct_Congruency_PSI';                                        % path to the parent directory where all new data will be stored (save structure: RecDate >> Animal >> Epoch >> all figures/files)
    
    sessions = dir(fullfile(datadir,'*.mat')); % bad naming convention but only ever one session at a time
    addpath(genpath(datadir));
    addpath(genpath(chandir));

     % make save folders and directory
    savedir = fullfile(savedir, RecDate, Animal, extractBefore(Epoch, 'Onset'), Behavior);
    if ~exist(savedir, 'dir')  % make folders if they don't exist already
       mkdir(savedir);
    end   
    
    % main loop 2: for every frequency band run the following 
    
    for fb = 1:length(freq_band_list)
    
        Frequency_Band = freq_band_list{fb};

        % Fetch the Condition_1 Channels (output of ChanWise_SpecEval)
        
        Condition_1_SigChans_fn = sprintf('SigChannels_%s_%s_%s_%s_%s.mat', RecDate, Epoch, 'OnlyPrior', Behavior, Frequency_Band);
        Condition_1_files = dir(fullfile(chandir, Condition_1_SigChans_fn));
                         
        if  isempty(Condition_1_files)

            % generate null output files if there are no sig. channels for Condition_1
            % this is supposed to stop the code because there is no point continuing if there either of the conditions are empty

            save_file_name = fullfile(savedir, sprintf('NULL_%s_%s_%s_%s_%s_%s_data.txt', Animal, RecDate, Epoch, RecDate, Frequency_Band,Behavior));
            fid4 = fopen(save_file_name, 'w');
            fclose('all');

        else % get the labels for the PFC channels and AC channels 
       
         
            Condition_1_SigChans = load(fullfile(chandir, Condition_1_SigChans_fn), 'significant_channels');
            Condition_1_modifiedCellArray   = regexprep(Condition_1_SigChans.significant_channels , '^(D1_|D2_|D3_|D4_)', '*');
        
            % Separate elements that start with *PFC and *AC
            Condition_1_PFC_chans  =  Condition_1_modifiedCellArray(startsWith(Condition_1_modifiedCellArray, '*PFC'));
            Condition_1_AC_chans   =  Condition_1_modifiedCellArray(startsWith(Condition_1_modifiedCellArray, '*AC'));
 
            % Fetch the Condition_2 Channels 
          
            Condition_2_SigChans_fn = sprintf('SigChannels_%s_%s_%s_%s_%s.mat', RecDate, Epoch, 'OnlyPretone', Behavior, Frequency_Band);
            Condition_2_files = dir(fullfile(chandir, Condition_2_SigChans_fn));

         
         if isempty(Condition_2_files)

              % generate null output files if there are no sig. channels for Condition_2
              % this is supposed to stop the code because there is no point continuing if there either of the conditions are empty
                                                
              save_file_name = fullfile(savedir, sprintf('NULL_%s_%s_%s_%s_%s_%s_data.txt', Animal, RecDate, Epoch, Frequency_Band,  Behavior));
              fid4 = fopen(save_file_name, 'w');
              fclose('all');
                                                
         else
    
             Condition_2_SigChans = load(fullfile(chandir, Condition_2_SigChans_fn), 'significant_channels');
             Condition_2_modifiedCellArray   = regexprep(Condition_2_SigChans.significant_channels , '^(D1_|D2_|D3_|D4_)', '*');
                        
             % Separate elements that start with *PFC and *AC
             Condition_2_PFC_chans  =  Condition_2_modifiedCellArray(startsWith(Condition_2_modifiedCellArray, '*PFC'));
             Condition_2_AC_chans   =  Condition_2_modifiedCellArray(startsWith(Condition_2_modifiedCellArray, '*AC'));
                   
             % Get the Channel Pairs that are shared by Condition 1 and
             % Condition 2; in the case of congruent and non-congruent
             % we pull sig chans only from the prioronly trials
    
             % now we build a matrix of all of the shared channel pairs 
    
             % Find common elements
             common_PFC_chans = intersect(Condition_1_PFC_chans, Condition_2_PFC_chans);
             common_AC_chans  = intersect(Condition_1_AC_chans, Condition_2_AC_chans);
    
             % Get all pairwise combinations
             [PFC_comb, AC_comb] = ndgrid(common_PFC_chans, common_AC_chans);
            
             % Reshape into Nx2 cell array
              Shared_ChannelPairs = [PFC_comb(:), AC_comb(:)];
                
             % generate null output files if there are no sig. channels for PretoneOnly Condition
             % the code could still carry on even if both conditions had sig channels, but should be stopped if there are zero shared channels pairs

          if isempty(Shared_ChannelPairs)

             save_file_name = fullfile(savedir, sprintf('NOSHAREDPAIRS_%s_%s_%s_%s_%s_%s_data.txt', Animal, RecDate, Epoch, RecDate, Frequency_Band, Behavior));
             fid4 = fopen(save_file_name, 'w');
             fclose('all');

          else

             % clear variables used to generate shared channel pairs
             clear_list = {'AC_comb', 'common_AC_chans', 'common_PFC_chans', 'files', 'PFC_comb', 'Condition_1_PFC_chans', 'Condition_2_PFC_chans', ...
                          'Condition_1_AC_chans', 'Condition_2_AC_chans', 'Condition_1_modifiedCellArray', 'Condition_2_modifiedCellArray', ...
                          'Condition_1_SigChans_fn', 'Condition_2_SigChans_fn', 'Condition_1_SigChans', 'Condition_2_SigChans'};

             clear(clear_list{:});
             clear clear_list;

             % extract session information
             baseFileName = sessions.name;
             fullFileName = fullfile(sessions.folder, baseFileName);
             fprintf(1, 'Now reading %s/n', fullFileName);
             V = load(fullfile(fullFileName));
            
             % set parameters required for fieldtrip functions and data selection
             params.choice = V.choice;
             params.err = V.err;
             params.pretone = V.pretone;
             params.pretoneLength = V.pretoneLength;
             params.prior = cell2char(V.prior); 
             params.SNR = V.SNR;
            
             % Recode the frequencies of the target at 'H' or 'L'rather than their frequency values. 
            
             unique_vals = unique(V.stim);  % Get the two unique values
            
             % Identify the higher (H) and lower (L) values

             high_val = max(unique_vals);
             low_val  = min(unique_vals);
            
             % Create V.target as a cell array

             V.target = cell(size(V.stim));  % Initialize V.target as a cell array
            
             % Assign 'H' for the higher value and 'L' for the lower value
             for i = 1:length(V.stim)
                if V.stim(i) == high_val
                    V.target{i} = 'H';  % Higher value
                else
                    V.target{i} = 'L';  % Lower value
                end
             end
            
             params.target = V.target;
            

             % Adds new field in data structure for OnlyPrior Trials that
             % indicates congruence between target and LED

            if strcmp(Condition,'OnlyPrior') ==1
             
             % Initialize V.congruency as a cell array as a new selection factor for select data function  

             V.congruency = cell(size(V.prior));  % Preallocate as a cell array
             
             % Loop through each element in V.prior and V.target

             for i = 1:length(V.prior)
                if strcmp(V.prior{i}, 'H') && strcmp(V.target{i}, 'H')
                    V.congruency{i} = 'congruent';  % If both are 'H'
                elseif strcmp(V.prior{i}, 'L') && strcmp(V.target{i}, 'L')
                    V.congruency{i} = 'congruent';  % If both are 'L'
                elseif strcmp(V.prior{i}, 'N')
                    V.congruency{i} = 'neutral';  % If prior is 'N'
                elseif (strcmp(V.prior{i}, 'H') && strcmp(V.target{i}, 'L')) || (strcmp(V.prior{i}, 'L') && strcmp(V.target{i}, 'H'))
                    V.congruency{i} = 'incongruent';  % If prior and target are different
                end
             end
            
             params.congruency = V.congruency;

            end

            % Adds new field in data structure for OnlyPrior Trials that
            % indicates congruence between target and pretone

            if strcmp(Condition,'OnlyPretone') == 1
             
             % Initialize V.congruency as a cell array as a new selection factor for select data function  

             V.congruency = cell(size(V.pretone));  % Preallocate as a cell array
             V.pretone = cellstr(V.pretone);
             
             % Loop through each element in V.pretone and V.target

             for i = 1:length(V.pretone)
                if strcmp(V.pretone{i}, 'H') && strcmp(V.target{i}, 'H')
                    V.congruency{i} = 'congruent';  % If both are 'H'
                elseif strcmp(V.pretone{i}, 'L') && strcmp(V.target{i}, 'L')
